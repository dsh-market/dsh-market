#!/usr/bin/env node
/**
 * One list of sponsors (sponsors.json) feeds every place they appear:
 *   - README.md / README.zh.md  — the block between the sponsors markers
 *   - src/client/sponsors.generated.ts — what the market shows (logos inlined)
 *   - the site strip, via sponsorStripHtml() used by build-site.mjs
 * The order of the list is the display order everywhere (highest sponsorship
 * first); amounts never go in this file.
 * `plugins` (optional): the sponsor's own plugins, by npm name or repo URL.
 * They stay at the front of the market's "Recently added" row, marked as
 * sponsored, for as long as the sponsorship runs; the mark links to the
 * sponsor with the `plugin` place's tag.
 * An entry with `until` (YYYY-MM-DD) drops out of all of them by itself once
 * that day has passed, so ending a sponsorship never needs a code change.
 * SPONSORS_FILE=other.json builds from a different list (previews).
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const esc = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;')

export function loadSponsors(file = process.env.SPONSORS_FILE ?? 'sponsors.json', today = new Date().toISOString().slice(0, 10)) {
  const list = JSON.parse(fs.readFileSync(path.join(ROOT, file), 'utf8'))
  return list.filter(s => s.until == null || s.until >= today)
}

const logoName = s => path.basename(s.site ?? s.logo)
/** Each place gets its own utm_content, so the sponsor can tell README, site and market clicks apart. */
export const linkFor = (s, place) => {
  // A sponsor may name its own tag for a place (`utm: { site: 'website' }`).
  const where = s.utm?.[place] ?? place
  return s.url
    .replace(/([?&]utm_content=)[^&]*/, `$1${where}`)
    // Some sponsors also track the placement in ad_group_id; keep it in step.
    .replace(/([?&]ad_group_id=)[^&]*/, `$1${where}`)
}

/** Title sponsors get a row with a paragraph; the rest share a logo wall. */
export function readmeBlock(list, lang) {
  if (list.length === 0) return ''
  const zh = lang === 'zh'
  const title = list.filter(s => s.tier === 'title')
  const rest = list.filter(s => s.tier !== 'title')
  let out = `## ${zh ? '赞助商' : 'Sponsors'}\n\n`
  if (title.length > 0) {
    out += '<table>\n'
    for (const s of title) {
      const name = zh ? s.name.zh : s.name.en
      const url = linkFor(s, 'readme')
      // `readmeBox`: a wide logo gets a square box as tall as the others'; the
      // image keeps its own proportions inside it (scaled, never stretched).
      const box = s.readmeBox ? ` height="${Number(s.readmeBox)}"` : ''
      const img = s.logoDark
        ? `<picture><source media="(prefers-color-scheme: dark)" srcset="${s.logoDark}"><img src="${s.logo}" alt="${esc(name)}" width="150"${box}></picture>`
        : `<img src="${s.logo}" alt="${esc(name)}" width="150"${box}>`
      const body = s.readme ? (zh ? s.readme.zh : s.readme.en).replaceAll('{url}', url) : name
      out += `<tr>\n<td width="180" align="center"><a href="${url}">${img}</a></td>\n<td>${body}</td>\n</tr>\n`
    }
    out += '</table>\n'
  }
  if (rest.length > 0) {
    out += `\n<p align="center">\n`
    for (const s of rest) {
      const name = zh ? s.name.zh : s.name.en
      out += `  <a href="${linkFor(s, 'readme')}" title="${esc(name)}"><img src="${s.logo}" alt="${esc(name)}" height="40"></a>&nbsp;&nbsp;\n`
    }
    out += '</p>\n'
  }
  return out
}

export function sponsorStripHtml(list, lang) {
  if (list.length === 0) return ''
  const zh = lang === 'zh'
  const items = list.map(s => {
    const name = zh ? s.name.zh : s.name.en
    const scope = zh ? s.scope.zh : s.scope.en
    return `<a href="${linkFor(s, 'site')}" rel="sponsored noopener" title="${esc(name)} · ${esc(scope)}"><img src="${zh ? '../' : ''}assets/${logoName(s)}" alt="${esc(name)}"${s.siteWidth ? ` style="max-width:${Number(s.siteWidth)}px"` : ''} loading="lazy"></a>`
  }).join('')
  return `<div class="sponsor"><div class="wrap"><span class="sponsorLabel">${zh ? '赞助商' : 'Sponsors'}</span>${items}</div></div>\n`
}

function clientModule(list) {
  const mime = f => f.endsWith('.svg') ? 'image/svg+xml' : f.endsWith('.png') ? 'image/png' : 'image/jpeg'
  const rows = list.map(s => ({
    id: s.id, name: s.name, scope: s.scope, url: linkFor(s, 'market'), until: s.until ?? null, plugins: s.plugins ?? [], pluginUrl: linkFor(s, 'plugin'), ...(s.markWidth ? { markWidth: Number(s.markWidth) } : {}),
    logo: `data:${mime(s.mark ?? s.logo)};base64,${fs.readFileSync(path.join(ROOT, s.mark ?? s.logo)).toString('base64')}`,
  }))
  return `// Generated by scripts/sponsors.mjs from sponsors.json — do not edit.\nexport const SPONSORS: ReadonlyArray<{ id: string; name: Record<'zh' | 'en' | 'ja', string>; scope: Record<'zh' | 'en' | 'ja', string>; url: string; until: string | null; plugins: string[]; pluginUrl: string; markWidth?: number; logo: string }> = ${JSON.stringify(rows, null, 2)}\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const list = loadSponsors()
  for (const [file, lang] of [['README.md', 'en'], ['README.zh.md', 'zh']]) {
    const p = path.join(ROOT, file)
    let s = fs.readFileSync(p, 'utf8')
    const block = `<!-- sponsors:start -->\n${readmeBlock(list, lang)}<!-- sponsors:end -->`
    s = /<!-- sponsors:start -->[\s\S]*<!-- sponsors:end -->/.test(s)
      ? s.replace(/<!-- sponsors:start -->[\s\S]*<!-- sponsors:end -->/, () => block)
      : s.replace(/\n## (Install|安装)\n/, (m) => `\n${block}\n${m}`)
    fs.writeFileSync(p, s)
  }
  fs.writeFileSync(path.join(ROOT, 'src/client/sponsors.generated.ts'), clientModule(list))
  console.log(`sponsors: ${list.length} active`)
}
